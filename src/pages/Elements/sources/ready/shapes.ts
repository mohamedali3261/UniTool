export const readyShapes: LibraryElement[] = definitions.map(
  ([name, n, inner], i) => {
    const layer = panel(
      `ready-shape-${i}`,
      50,
      50,
      260,
      260,
      palette[i % 5],
      0,
    );
    const points = inner
      ? Array.from({ length: inner === 1 ? n : n * 2 }, (_, k) => {
          const a =
              -Math.PI / 2 + (k * Math.PI * 2) / (inner === 1 ? n : n * 2),
            r = inner === 1 || k % 2 === 0 ? 1 : inner;
          return { x: Math.cos(a) * r, y: Math.sin(a) * r };
        })
      : custom[n].map(([x, y]) => ({ x, y }));
    layer.name = name;
    layer.box!.points = points;
    return {
      id: `ready-shape-${i}`,
      name,
      source: "unitool-ready",
      sourceName: "UniTool Ready",
      kind: "layer",
      category: "shapes",
      layer,
      animated: false,
    };
  },
);
